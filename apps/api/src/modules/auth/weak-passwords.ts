/**
 * The common-password blocklist (`P1-AUTH-01`, `docs/14-security.md` §3).
 *
 * Password creation rejects anything on this list. The owner's requirement is "not in a small weak-password
 * list", and this is the smallest list that is *credible*: the 1 000 most-used passwords of the
 * **Django** project's published blocklist (`django/contrib/auth/common-passwords.txt.gz`, 19 640 entries,
 * file sha `c23afebf306a8a715638fbb08e31ee92738173f6`), in its own frequency order. Derived data, taken
 * verbatim — not re-sorted, not re-typed, no entries added by hand.
 *
 * Provenance and licence: Django is BSD-3-Clause (Copyright © Django Software Foundation and individual
 * contributors). Shipping 1 000 of its lines as a lookup table is the intended use of that list, and the
 * licence notice is reproduced here rather than in a separate file because this module is the only copy.
 *
 * **Why the frequency order is kept.** It is the only ordering with information in it, and it lets a future
 * pass cut the list from the tail (the entries least likely to be tried) without re-deriving anything.
 *
 * **Matching is not exact-string** — see `password.ts`: the candidate is case-folded and stripped of trailing
 * digits and symbols first, so `Password2026!` matches `password`. Measured consequence, worth knowing when
 * this list is maintained: only **9** of these 1 000 entries are 12 characters or longer, so the raw list
 * alone would almost never fire against a policy floor of 12 characters. The normalisation is what makes the
 * list matter, and it is also its limit: a weak stem with substitutions (`p@ssw0rd2026`) or repetitions
 * (`adminadmin12`) is not caught. This is a floor, not a guarantee.
 *
 * @module modules/auth/weak-passwords
 */

