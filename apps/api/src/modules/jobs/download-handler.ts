/**
 * Streamed, resumable Geofabrik downloads for the worker (`P2-JOB-05`, CACHE-1).
 *
 * The handler delegates every cache path and filesystem mutation to the storage module. It retains responsibility for
 * source identity, checksum and size verification, and the database lifecycle of the pending/ready version row.
 *
 * @module modules/jobs/download-handler
 */

import { basename } from 'node:path';

import { sql } from 'kysely';

import {
  hashFile,
  streamDownloadToPart,
  writeAll,
  type DownloadChunkWriter,
  type DownloadFetch,
} from '../../lib/download';
import { z } from 'zod';

import type { Job, JsonValue } from '../../db/schema';
import { withTransaction } from '../../db/transaction';
import { fetchGeofabrikMd5 } from '../geofabrik/file-metadata';
import type { MapSource, ResolvedDownload } from '../geofabrik/source';
import { createCacheStorage, type CacheStorage, type StorageFile } from '../storage/storage';
import type { JobHandler, JobHandlerContext } from './worker';

/** UUIDs are generated by PostgreSQL and are the only job-derived path component. */
const UUID_PATTERN = /^[\da-f]{8}-(?:[\da-f]{4}-){3}[\da-f]{12}$/iu;
/** Database map-version constraint: lower-case or upper-case alphanumerics plus `._@+-`. */
const VERSION_PATTERN = /^[A-Za-z0-9][A-Za-z0-9._@+-]{0,63}$/u;
const DownloadPayloadSchema = z.object({
  countryId: z.uuid(),
  version: z.string().trim().min(1).max(64),
  origin: z.string().optional(),
  onlyIfChanged: z.boolean().optional(),
});

/** Dependencies of the registered download worker handler. */
export interface DownloadHandlerOptions {
  /** Source resolver for Geofabrik metadata and direct download locations. */
  readonly source: MapSource;
  /** Cache root on a persistent filesystem. */
  readonly cacheDirectory: string;
  /** Injected transport; defaults to the platform fetch implementation. */
  readonly fetchImpl?: DownloadFetch;
  /** Low-level write seam for deterministic filesystem-failure tests. */
  readonly writeChunk?: DownloadChunkWriter;
  /** Clock for the immutable identity of a `latest` request with no source timestamp. */
  readonly now?: () => Date;
}

/** Safe, non-secret failure type used to distinguish local integrity and capacity failures in tests/logs. */
export class DownloadHandlerError extends Error {
  /** Stable internal category; the worker intentionally persists its generic JOB_HANDLER_FAILED contract. */
  readonly code:
    'DOWNLOAD_INVALID_RESPONSE' | 'DOWNLOAD_CHECKSUM_MISMATCH' | 'DOWNLOAD_STORAGE_FAILED';

  constructor(code: DownloadHandlerError['code'], message: string, options?: ErrorOptions) {
    super(message, options);
    this.name = 'DownloadHandlerError';
    this.code = code;
  }
}

interface PreparedDownload {
  readonly version: string;
  readonly origin: 'geofabrik_snapshot' | 'geofabrik_latest';
  readonly filename: string;
  readonly relativeStoragePath: string;
  readonly storageFile: StorageFile;
  readonly partFile: StorageFile;
  readonly expectedMd5: string;
  readonly expectedSize: bigint | null;
  readonly source: ResolvedDownload;
}

/**
 * Builds the worker handler. `server.ts` registers it alongside the catalog-sync handler with the composed Geofabrik
 * `MapSource`; tests exercise this factory through the actual worker contract.
 *
 * @param options - Source, cache root, transport and optional clock.
 * @returns A `download` handler suitable for `JobHandlers`.
 */
export function createDownloadHandler(options: DownloadHandlerOptions): JobHandler {
  const storage = createCacheStorage(options.cacheDirectory);
  const fetchImpl = options.fetchImpl ?? globalThis.fetch;
  const writeChunk = options.writeChunk ?? writeAll;
  const now = options.now ?? (() => new Date());
  return async (job, context) => {
    try {
      return await runDownload(job, context, options.source, storage, fetchImpl, writeChunk, now);
    } catch (error) {
      // Cancellation may happen before source resolution or checksum lookup, before the main transfer cleanup scope.
      if ((context.signal.aborted || isCancellation(error)) && UUID_PATTERN.test(job.id)) {
        await storage
          .partFile(job.id)
          .remove()
          .catch(() => undefined);
        await context.database
          .updateTable('map_versions')
          .set({ status: 'failed', failure_reason: 'CANCELED', ready_at: null })
          .where('job_id', '=', job.id)
          .where('status', '=', 'pending')
          .execute()
          .catch(() => undefined);
      }
      throw error;
    }
  };
}

async function runDownload(
  job: Job,
  context: JobHandlerContext,
  source: MapSource,
  storage: CacheStorage,
  fetchImpl: DownloadFetch,
  writeChunk: DownloadChunkWriter,
  now: () => Date,
): Promise<JsonValue> {
  if (job.type !== 'download') throw new TypeError('download handler received a non-download job');
  const payload = DownloadPayloadSchema.parse(job.payload);
  assertNotAborted(context.signal);

  const country = await context.database
    .selectFrom('countries')
    .select(['id', 'slug', 'source_id'])
    .where('id', '=', payload.countryId)
    .executeTakeFirst();
  if (country === undefined) throw new Error('download country no longer exists');
  if (!/^[a-z0-9][a-z0-9-]{0,63}$/u.test(country.slug)) {
    throw new DownloadHandlerError(
      'DOWNLOAD_INVALID_RESPONSE',
      'Catalog slug is not safe for storage.',
    );
  }

  const resolved = await source.resolveDownload(country.source_id, payload.version, context.signal);
  assertNotAborted(context.signal);
  const prepared = await prepareDownload(
    job,
    payload.version,
    country.slug,
    resolved,
    storage,
    fetchImpl,
    context.signal,
    now,
  );
  const existing = await reserveVersionSlot(context.database, job, payload.countryId, prepared);
  if (existing !== null) {
    const installed = await hashFile(prepared.storageFile, context.signal);
    if (
      installed.checksum !== prepared.expectedMd5 ||
      (prepared.expectedSize !== null && installed.size !== prepared.expectedSize)
    ) {
      throw new DownloadHandlerError(
        'DOWNLOAD_CHECKSUM_MISMATCH',
        'The cached file does not match the current source identity.',
      );
    }
    return { versionId: existing, version: prepared.version };
  }

  await context.reportProgress({
    progressBytes: 0n,
    totalBytes: prepared.expectedSize,
    phase: 'downloading',
  });
  let partMayBeKept = true;
  let installed = false;
  try {
    await prepared.partFile.ensureParent();
    await prepared.storageFile.ensureParent();
    const etag = prepared.source.etag;
    const strongEtag = etag !== null && !/^W\//iu.test(etag) ? etag : null;
    await streamDownloadToPart({
      url: prepared.source.url,
      part: prepared.partFile,
      expectedSize: prepared.expectedSize,
      mutable: prepared.origin === 'geofabrik_latest',
      validator: strongEtag ?? prepared.source.lastModified?.toUTCString() ?? null,
      progressFloor: BigInt(job.progress_bytes),
      signal: context.signal,
      reportProgress: context.reportProgress,
      fetchImpl,
      writeChunk,
    });
    assertNotAborted(context.signal);

    await context.reportProgress({
      progressBytes: await prepared.partFile.size(),
      totalBytes: prepared.expectedSize,
      phase: 'verifying',
    });
    const { checksum, size } = await hashFile(prepared.partFile, context.signal);
    if (size <= 0n || (prepared.expectedSize !== null && size !== prepared.expectedSize)) {
      throw new DownloadHandlerError(
        'DOWNLOAD_INVALID_RESPONSE',
        'Downloaded file length did not match source metadata.',
      );
    }
    if (checksum !== prepared.expectedMd5) {
      partMayBeKept = false;
      throw new DownloadHandlerError(
        'DOWNLOAD_CHECKSUM_MISMATCH',
        'Downloaded file did not match the source MD5.',
      );
    }

    assertNotAborted(context.signal);
    // The pending slot for (country,version) serializes installation; storage verifies both paths and renames on CACHE_DIR.
    await storage.installPart(prepared.partFile, prepared.storageFile);
    partMayBeKept = false;
    installed = true;
    const versionId = await finalizeVersion(
      context.database,
      job,
      payload.countryId,
      prepared,
      size,
    );
    await context.reportProgress({ progressBytes: size, totalBytes: size, phase: 'installing' });
    return { versionId, version: prepared.version };
  } catch (error) {
    if (context.signal.aborted || isCancellation(error) || isNoSpace(error)) partMayBeKept = false;
    if (!partMayBeKept) await prepared.partFile.remove().catch(() => undefined);
    if (installed) await prepared.storageFile.remove().catch(() => undefined);
    await failVersion(
      context.database,
      job.id,
      payload.countryId,
      prepared.version,
      failureReason(error),
    );
    if (isNoSpace(error)) {
      throw new DownloadHandlerError(
        'DOWNLOAD_STORAGE_FAILED',
        'The cache filesystem could not store the download.',
        {
          cause: error,
        },
      );
    }
    throw error;
  }
}

async function prepareDownload(
  job: Job,
  requestedVersion: string,
  slug: string,
  source: ResolvedDownload,
  storage: CacheStorage,
  fetchImpl: DownloadFetch,
  signal: AbortSignal,
  now: () => Date,
): Promise<PreparedDownload> {
  if (!UUID_PATTERN.test(job.id)) throw new TypeError('job id is not a UUID');
  const url = parseDownloadUrl(source.url);
  const fromUrl = safeFilename(url.pathname);
  const filename = fromUrl;
  const latest = requestedVersion === 'latest';
  const timestamp = source.dataTimestamp ?? now();
  const latestVersion = `latest@${timestamp
    .toISOString()
    .replace(/:/gu, '-')
    .replace(/\.\d{3}Z$/u, 'Z')}`;
  const version = latest ? latestVersion : (source.version ?? requestedVersion);
  if (!VERSION_PATTERN.test(version)) {
    throw new DownloadHandlerError(
      'DOWNLOAD_INVALID_RESPONSE',
      'Source returned an invalid version identity.',
    );
  }
  if (!latest && source.version !== null && source.version !== requestedVersion) {
    throw new DownloadHandlerError(
      'DOWNLOAD_INVALID_RESPONSE',
      'Source resolved a different dated version.',
    );
  }
  const expectedSize = source.sizeBytes === null ? null : BigInt(validateSize(source.sizeBytes));
  const expectedMd5 =
    source.checksumMd5 ??
    (await fetchGeofabrikMd5(source.url, {
      fetchImpl,
      timeoutMs: 30_000,
      maxAttempts: 3,
      retryDelayMs: 100,
      signal,
    }));
  if (!/^[a-f\d]{32}$/iu.test(expectedMd5)) {
    throw new DownloadHandlerError(
      'DOWNLOAD_INVALID_RESPONSE',
      'Source returned an invalid MD5 checksum.',
    );
  }
  const storageFile = storage.versionFile(slug, version, filename);
  const partFile = storage.partFile(job.id);
  const relativeStoragePath = storageFile.relativePath;
  return {
    version,
    origin: latest ? 'geofabrik_latest' : 'geofabrik_snapshot',
    filename,
    relativeStoragePath,
    storageFile,
    partFile,
    expectedMd5: expectedMd5.toLowerCase(),
    expectedSize,
    source,
  };
}

async function reserveVersionSlot(
  database: JobHandlerContext['database'],
  job: Job,
  countryId: string,
  prepared: PreparedDownload,
): Promise<string | null> {
  return withTransaction(database, async (trx) => {
    const current = await trx
      .selectFrom('map_versions')
      .select(['id', 'status', 'job_id', 'checksum_md5', 'file_size_bytes', 'storage_path'])
      .where('country_id', '=', countryId)
      .where('version', '=', prepared.version)
      .forUpdate()
      .executeTakeFirst();
    if (current?.status === 'ready') {
      if (
        current.checksum_md5 !== prepared.expectedMd5 ||
        current.storage_path !== prepared.relativeStoragePath ||
        (prepared.expectedSize !== null &&
          BigInt(current.file_size_bytes) !== prepared.expectedSize)
      ) {
        throw new DownloadHandlerError(
          'DOWNLOAD_CHECKSUM_MISMATCH',
          'The stored version conflicts with the current source identity.',
        );
      }
      return current.id;
    }
    if (current?.status === 'pending' && current.job_id !== job.id) {
      const owner =
        current.job_id === null
          ? undefined
          : await trx
              .selectFrom('jobs')
              .select('status')
              .where('id', '=', current.job_id)
              .executeTakeFirst();
      if (owner?.status === 'running' || owner?.status === 'queued') {
        throw new Error('another download currently owns this version');
      }
    }
    if (current === undefined) {
      await trx
        .insertInto('map_versions')
        .values({
          country_id: countryId,
          version: prepared.version,
          origin: prepared.origin,
          source_url: prepared.source.url,
          source_filename: prepared.filename,
          data_timestamp: prepared.source.dataTimestamp,
          file_size_bytes: prepared.expectedSize ?? 0n,
          checksum_md5: prepared.expectedMd5,
          checksum_sha256: null,
          storage_path: prepared.relativeStoragePath,
          status: 'pending',
          failure_reason: null,
          job_id: job.id,
          uploaded_by: null,
        })
        .execute();
    } else {
      await trx
        .updateTable('map_versions')
        .set({
          origin: prepared.origin,
          source_url: prepared.source.url,
          source_filename: prepared.filename,
          data_timestamp: prepared.source.dataTimestamp,
          file_size_bytes: prepared.expectedSize ?? 0n,
          checksum_md5: prepared.expectedMd5,
          storage_path: prepared.relativeStoragePath,
          status: 'pending',
          failure_reason: null,
          job_id: job.id,
          ready_at: null,
        })
        .where('id', '=', current.id)
        .execute();
    }
    await trx
      .insertInto('country_cache')
      .values({ country_id: countryId })
      .onConflict((conflict) => conflict.column('country_id').doNothing())
      .execute();
    return null;
  });
}

async function finalizeVersion(
  database: JobHandlerContext['database'],
  job: Job,
  countryId: string,
  prepared: PreparedDownload,
  size: bigint,
): Promise<string> {
  return withTransaction(database, async (trx) => {
    const version = await trx
      .updateTable('map_versions')
      .set({
        file_size_bytes: size,
        checksum_md5: prepared.expectedMd5,
        status: 'ready',
        failure_reason: null,
        job_id: job.id,
        ready_at: new Date(),
      })
      .where('country_id', '=', countryId)
      .where('version', '=', prepared.version)
      .where('status', '=', 'pending')
      .where('job_id', '=', job.id)
      .returning('id')
      .executeTakeFirst();
    if (version === undefined)
      throw new Error('download version slot is no longer owned by this job');

    await trx
      .insertInto('country_cache')
      .values({ country_id: countryId })
      .onConflict((conflict) => conflict.column('country_id').doNothing())
      .execute();
    await trx
      .updateTable('country_cache')
      .set({
        versions_ready_count: sql<number>`(
          select count(*)::integer from map_versions
           where country_id = ${countryId} and status = 'ready'
        )`,
        total_size_bytes: sql<bigint>`(
          select coalesce(sum(file_size_bytes), 0)::bigint from map_versions
           where country_id = ${countryId} and status = 'ready'
        )`,
        updated_at: new Date(),
      })
      .where('country_id', '=', countryId)
      .execute();
    return version.id;
  });
}

async function failVersion(
  database: JobHandlerContext['database'],
  jobId: string,
  countryId: string,
  version: string,
  reason: string,
): Promise<void> {
  await database
    .updateTable('map_versions')
    .set({ status: 'failed', failure_reason: reason, ready_at: null })
    .where('country_id', '=', countryId)
    .where('version', '=', version)
    .where('job_id', '=', jobId)
    .where('status', '=', 'pending')
    .execute();
}

function parseDownloadUrl(value: string): URL {
  let url: URL;
  try {
    url = new URL(value);
  } catch (error) {
    throw new DownloadHandlerError(
      'DOWNLOAD_INVALID_RESPONSE',
      'Source returned an invalid download URL.',
      {
        cause: error,
      },
    );
  }
  if (
    (url.protocol !== 'http:' && url.protocol !== 'https:') ||
    url.username !== '' ||
    url.password !== ''
  ) {
    throw new DownloadHandlerError(
      'DOWNLOAD_INVALID_RESPONSE',
      'Source returned an unsafe download URL.',
    );
  }
  return url;
}

function safeFilename(pathname: string): string {
  let decoded: string;
  try {
    decoded = decodeURIComponent(basename(pathname));
  } catch (error) {
    throw new DownloadHandlerError(
      'DOWNLOAD_INVALID_RESPONSE',
      'Source returned an invalid filename.',
      {
        cause: error,
      },
    );
  }
  if (
    decoded.length === 0 ||
    decoded === '.' ||
    decoded === '..' ||
    decoded.includes('/') ||
    decoded.includes('\\') ||
    decoded.includes('\0') ||
    !/^[A-Za-z0-9][A-Za-z0-9._+-]{0,199}\.osm\.pbf$/u.test(decoded)
  ) {
    throw new DownloadHandlerError(
      'DOWNLOAD_INVALID_RESPONSE',
      'Source returned an unsafe filename.',
    );
  }
  return decoded;
}

function validateSize(value: number): number {
  if (!Number.isSafeInteger(value) || value < 0) {
    throw new DownloadHandlerError(
      'DOWNLOAD_INVALID_RESPONSE',
      'Source returned an invalid content length.',
    );
  }
  return value;
}

function assertNotAborted(signal: AbortSignal): void {
  if (signal.aborted)
    throw signal.reason instanceof Error ? signal.reason : new Error('download canceled');
}

function isCancellation(error: unknown): boolean {
  return (
    error instanceof Error &&
    (error.name === 'AbortError' || error.name === 'JobOwnershipLostError')
  );
}

function isNoSpace(error: unknown): boolean {
  return hasCode(error, 'ENOSPC') || hasCode(error, 'EDQUOT');
}

function hasCode(error: unknown, code: string): boolean {
  return typeof error === 'object' && error !== null && 'code' in error && error.code === code;
}

function failureReason(error: unknown): string {
  if (error instanceof DownloadHandlerError) return error.code;
  if (isNoSpace(error)) return 'DISK_FULL';
  if (isCancellation(error)) return 'CANCELED';
  return 'DOWNLOAD_FAILED';
}
